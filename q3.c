#include <stdio.h>

int main(void)
{
	float table[4][5];
	float total_product[5] = {0};
	float total_person[4] = {0};
	int i, j;
	int expensive_index = 0;
	int bonus[4] = {0};
	
	for (i = 0; i < 4; i++)
	{
		for (j = 0; j < 5; j++)
		{
			do
			{
				printf("Input sales amount in rupees earned by salesman %d for product %d: ", i + 1, j + 1);
				scanf("%f", &table[i][j]);
			}
			while (table[i][j] < 0);
			total_product[j] = total_product[j] + table[i][j];
			total_person[i] = total_person[i] + table[i][j];
		}
	}
	
	for (i = 0; i < 5; i++)
	{
		if (total_product[i] > total_product[expensive_index])
		{
			expensive_index = i;
		}
	}
		
	for (i = 0; i < 4; i++)
	{
		if (total_person[i] >= 10000)
		{
			total_person[i] *= 1.1;
			bonus[i] = 1;
		}
	}
	printf("\n");
	for (i = 0; i < 4; i++)
	{
		if (bonus[i] == 1)
		{
			printf("total sales by salesman %d: %0.1f (bonus of 10%% applied)\n", i + 1, total_person[i]);
		}
		else
		{
			printf("total sales by salesman %d: %0.1f\n", i + 1, total_person[i]);
		}
	}
	
	printf("\n");
	
	for (i = 0; i < 5; i++)
	{
		printf("total sales of product %d: %0.1f\n", i + 1, total_product[i]);
	}		
	
	printf("\nhighest revenue generated by: Product %d.\n", expensive_index + 1);
	
	return 0;
}
